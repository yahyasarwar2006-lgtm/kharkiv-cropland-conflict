"""Data-quality report for the panel: where and when NDVI is empty (no clear image,
or less than the minimum clear share of cropland), and how long the gaps are.

Run after scripts/build_panel.py:
    python scripts/data_quality_report.py
Output: reports/data_quality.md, reports/figures/panel_empty_ndvi.png
"""

from pathlib import Path

import geopandas as gpd
import matplotlib.pyplot as plt
import pandas as pd

from agridisrupt.config import load_config

PEAK_PERIODS = [5, 6, 7, 8]   # 10 Jun - 4 Aug: when summer crops are greenest


def longest_gap(empty: pd.Series) -> int:
    """Longest run of consecutive True values (empty periods) in one season."""
    runs = (empty != empty.shift()).cumsum()
    return int(empty.groupby(runs).sum().max())


def pct_table(df: pd.DataFrame, by: str) -> pd.DataFrame:
    g = df.groupby(by)
    return pd.DataFrame({
        "no clear image %": g["ndvi_raw"].apply(lambda s: s.isna().mean() * 100),
        "below rule %": g.apply(lambda d: (d["ndvi_raw"].notna() & d["ndvi"].isna()).mean() * 100),
        "empty total %": g["ndvi"].apply(lambda s: s.isna().mean() * 100),
    }).round(1)


def main():
    config = load_config("configs/kharkiv_v1.yaml")
    min_valid = config["panel"]["min_valid_share"]
    panel = pd.read_csv(Path(config["paths"]["data_processed"]) / "panel.csv")
    panel["empty"] = panel["ndvi"].isna()

    by_year = pct_table(panel, "year")
    by_period = pct_table(panel, "period")
    by_period.insert(0, "starts", panel.groupby("period")["period_start"].first().str[5:])
    by_tile = pct_table(panel, "tile")

    seasons = panel.groupby(["cell_id", "year"])
    gaps = seasons["empty"].apply(longest_gap)
    peak_seen = panel[panel["period"].isin(PEAK_PERIODS)].groupby(["cell_id", "year"])["empty"].agg(lambda e: (~e).sum())
    per_cell = panel.groupby("cell_id")["empty"].mean() * 100

    # Figure: empty share per year x period, and per cell on the map
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(13, 4.6), gridspec_kw={"width_ratios": [1.2, 1]})
    heat = panel.pivot_table(index="year", columns="period", values="empty", aggfunc="mean") * 100
    im = ax1.imshow(heat.values, cmap="Reds", vmin=0, vmax=max(30, heat.values.max()), aspect="auto")
    ax1.set_xticks(range(heat.shape[1]), by_period["starts"], rotation=60, fontsize=7)
    ax1.set_yticks(range(heat.shape[0]), heat.index)
    for (i, j), v in pd.DataFrame(heat.values).stack().items():
        if v >= 5:
            ax1.text(j, i, f"{v:.0f}", ha="center", va="center", fontsize=6.5)
    ax1.set_title("Empty NDVI per 14-day period (% of 1,192 cells)", fontsize=10)
    fig.colorbar(im, ax=ax1, shrink=0.8, label="%")

    cells = gpd.read_file(Path(config["paths"]["data_interim"]) / "kharkiv_grid_5km_cropland.gpkg")
    cells = cells.merge(per_cell.rename("empty_pct").reset_index(), on="cell_id")
    cells.plot(column="empty_pct", cmap="Reds", legend=True, ax=ax2, vmin=0,
               legend_kwds={"label": "% of all periods empty", "shrink": 0.8})
    ax2.set_title("Empty NDVI per 5 km cell, 2018–2024", fontsize=10)
    ax2.set_axis_off()
    fig.tight_layout()
    fig_path = Path(config["paths"]["reports_figures"]) / "panel_empty_ndvi.png"
    fig.savefig(fig_path, dpi=150)

    n_seasons = len(gaps)
    lines = [
        "# Data-quality report — panel (NDVI + climate)",
        "",
        "Generated by `scripts/data_quality_report.py` from `data/processed/panel.csv`.",
        f"Rule (config `panel.min_valid_share`): NDVI is kept only if >= {min_valid:.0%} of the cell's "
        "cropland was clear in the 14-day period; `ndvi_raw` keeps every value.",
        "",
        "## Overall",
        f"- Rows: {len(panel):,} ({panel['cell_id'].nunique()} cells x {panel['year'].nunique()} years x "
        f"{panel['period'].nunique()} periods). Climate columns: no missing values.",
        f"- No clear image at all: {panel['ndvi_raw'].isna().mean():.1%}. "
        f"Below the {min_valid:.0%} rule: {(panel['ndvi_raw'].notna() & panel['empty']).mean():.1%}. "
        f"**Empty in total: {panel['empty'].mean():.1%}.**",
        f"- Negative NDVI left after the rule: {int((panel['ndvi'] < 0).sum())}.",
        "",
        "## Per year", "```", by_year.to_string(), "```",
        "",
        "## Per 14-day period (all years)", "```", by_period.to_string(), "```",
        "",
        "## Per satellite tile", "```", by_tile.to_string(), "```",
        "",
        "## Per cell",
        f"- Share of periods empty per cell: median {per_cell.median():.1f}%, "
        f"90th percentile {per_cell.quantile(0.9):.1f}%, worst {per_cell.max():.1f}% ({per_cell.idxmax()}).",
        f"- Cells with more than 20% of periods empty: {int((per_cell > 20).sum())}.",
        "",
        "## Gaps inside a season (cell x year, 15 periods each)",
        f"- Seasons: {n_seasons:,}. Longest run of consecutive empty periods:",
        "```", gaps.value_counts().sort_index().rename("seasons").to_string(), "```",
        f"- Seasons with a gap of 3+ periods (6+ weeks): {int((gaps >= 3).sum())} "
        f"({(gaps >= 3).mean():.1%}).",
        f"- Seasons with NO clear value in the summer peak (periods {PEAK_PERIODS[0]}-{PEAK_PERIODS[-1]}, "
        f"10 Jun - 4 Aug): {int((peak_seen == 0).sum())}; with only 1 of 4: {int((peak_seen == 1).sum())}.",
        "",
        "![empty NDVI](figures/panel_empty_ndvi.png)",
    ]
    out = fig_path.parent.parent / "data_quality.md"   # reports/, next to figures/
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    print(f"\nSaved {out} and {fig_path}")


if __name__ == "__main__":
    main()
